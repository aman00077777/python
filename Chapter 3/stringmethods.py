str = "Janvi"
print(str)
print(str.upper())  # Convert to uppercase
print(str.lower())  # Convert to lowercase
print(str.capitalize())  # Capitalize first letter
print(str.replace("J", "A"))  # Replace character
print(str.find("n"))  # Find index of character
print(str.split("a"))  # Split string by character
print(str.strip())  # Remove leading/trailing whitespace
print(str.startswith("Ja"))  # Check if string starts with substring
print(str.endswith("vi"))  # Check if string ends with substring
print(str.title())  # Convert to title case
print(str.count("a"))  # Count occurrences of character